create extension if not exists pgcrypto;

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  position integer not null default 0
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  price numeric not null check (price > 0),
  category text not null,
  description text not null default '',
  images jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.site_settings (
  key text primary key,
  value text not null
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.site_settings enable row level security;
alter table public.admins enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.admins where user_id = auth.uid()) $$;

grant execute on function public.is_admin() to anon, authenticated;

create policy "Public catalog read" on public.categories for select using (true);
create policy "Public products read" on public.products for select using (true);
create policy "Public settings read" on public.site_settings for select using (true);
create policy "Admins manage categories" on public.categories for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Admins manage products" on public.products for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "Admins manage settings" on public.site_settings for all to authenticated using (public.is_admin()) with check (public.is_admin());

insert into public.categories (name, position) values
  ('Рогожка', 0), ('Велюр', 1), ('Жаккард', 2), ('Шенилл', 3), ('Кожа', 4)
on conflict (name) do nothing;
insert into public.site_settings (key, value) values ('background_image', 'background.jpg')
on conflict (key) do nothing;

